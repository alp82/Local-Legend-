// Draws the placeholder site icons from src/lib/siteTypes.ts into assets/overlays/
// (1x, 2x and 3x PNGs) and writes src/components/overlay-icons.ts, the static require
// table Metro needs. Built-in modules only. Run from mobile/:
//   node scripts/generate-overlay-icons.mjs
// Needs Node 23.6+ (type stripping) to import the .ts table directly.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { deflateSync } from 'node:zlib';

import { allSiteIcons } from '../src/lib/siteTypes.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'assets', 'overlays');
const SIZE = 28; // dp at 1x
const SUPERSAMPLE = 4;

const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});

function crc32(buf) {
  let c = 0xffffffff;
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([len, body, crc]);
}

function png(width, height, rgba) {
  const raw = Buffer.alloc((width * 4 + 1) * height);
  for (let y = 0; y < height; y++) {
    raw[y * (width * 4 + 1)] = 0; // filter: none
    rgba.copy(raw, y * (width * 4 + 1) + 1, y * width * 4, (y + 1) * width * 4);
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 6; // RGBA
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

const hex = (c) => [1, 3, 5].map((i) => parseInt(c.slice(i, i + 2), 16));

/** Inside test in unit coordinates (-1..1), r = scale of the shape. */
function inShape(shape, x, y, r) {
  if (shape === 'circle') return x * x + y * y <= r * r;
  // Rounded square.
  const k = 0.28 * r;
  const ax = Math.abs(x) - (r - k);
  const ay = Math.abs(y) - (r - k);
  if (ax <= 0 || ay <= 0) return Math.abs(x) <= r && Math.abs(y) <= r;
  return ax * ax + ay * ay <= k * k;
}

/** Badge: dark rim, white ring, colored fill, pictogram. Returns straight RGBA. */
function draw(type, px) {
  const fill = hex(type.color);
  const ink = hex(type.ink ?? '#ffffff');
  const rim = [29, 36, 51];
  const white = [255, 255, 255];
  const rgba = Buffer.alloc(px * px * 4);
  const g = type.glyph;
  const gn = g.length;
  const glyphHalf = type.shape === 'circle' ? 0.5 : 0.55;
  for (let py = 0; py < px; py++) {
    for (let pxl = 0; pxl < px; pxl++) {
      let r = 0;
      let gg = 0;
      let b = 0;
      let a = 0;
      for (let sy = 0; sy < SUPERSAMPLE; sy++) {
        for (let sx = 0; sx < SUPERSAMPLE; sx++) {
          const x = ((pxl + (sx + 0.5) / SUPERSAMPLE) / px) * 2 - 1;
          const y = ((py + (sy + 0.5) / SUPERSAMPLE) / px) * 2 - 1;
          let c = null;
          if (inShape(type.shape, x, y, 0.74)) {
            const gx = Math.floor(((x + glyphHalf) / (2 * glyphHalf)) * gn);
            const gy = Math.floor(((y + glyphHalf) / (2 * glyphHalf)) * gn);
            c = gx >= 0 && gy >= 0 && gx < gn && gy < gn && g[gy][gx] === '#' ? ink : fill;
          } else if (inShape(type.shape, x, y, 0.86)) c = white;
          else if (inShape(type.shape, x, y, 0.98)) c = rim;
          if (c) {
            r += c[0];
            gg += c[1];
            b += c[2];
            a += 1;
          }
        }
      }
      const i = (py * px + pxl) * 4;
      if (a > 0) {
        rgba[i] = Math.round(r / a);
        rgba[i + 1] = Math.round(gg / a);
        rgba[i + 2] = Math.round(b / a);
        rgba[i + 3] = Math.round((255 * a) / (SUPERSAMPLE * SUPERSAMPLE));
      }
    }
  }
  return rgba;
}

mkdirSync(outDir, { recursive: true });
const icons = allSiteIcons();
for (const type of icons) {
  for (const scale of [1, 2, 3]) {
    const px = SIZE * scale;
    const suffix = scale === 1 ? '' : `@${scale}x`;
    writeFileSync(join(outDir, `${type.icon}${suffix}.png`), png(px, px, draw(type, px)));
  }
}

const table = icons.map((t) => `  '${t.icon}': require('@/assets/overlays/${t.icon}.png'),`).join('\n');
writeFileSync(
  join(root, 'src', 'components', 'overlay-icons.ts'),
  `// Generated by scripts/generate-overlay-icons.mjs from src/lib/siteTypes.ts. Do not edit.
import type { ImageRequireSource } from 'react-native';

export const OVERLAY_ICONS: Record<string, ImageRequireSource> = {
${table}
};
`,
);
console.log(`Wrote ${icons.length} icons x 3 scales to assets/overlays/`);
